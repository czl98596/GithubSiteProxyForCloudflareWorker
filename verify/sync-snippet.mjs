import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = fs.readFileSync(path.join(root, 'src/index.js'), 'utf8').replace(/\r\n/g, '\n');
const listener = "addEventListener('fetch', event => {\n  event.respondWith(handleRequest(event.request, event));\n});";
if (!source.includes(listener)) throw new Error('Default entrypoint shape changed; review snippet generation');
const snippet = source
  .replace("const proxy_entry = 'index';", "const proxy_entry = 'snippet';")
  .replace('const inject_analytics = false;', 'const inject_analytics = true;')
  .replace(listener, 'export default {\n  async fetch(request, env, ctx) {\n    return handleRequest(request, ctx);\n  }\n};');
const generated = '// Generated by npm run sync:snippet; edit src/index.js first.\n' + snippet;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path.join(root, 'src/snippet.js'), 'utf8').replace(/\r\n/g, '\n') !== generated) {
    throw new Error('Entrypoints have drifted; run npm run sync:snippet');
  }
} else {
  fs.writeFileSync(path.join(root, 'src/snippet.js'), generated);
}
